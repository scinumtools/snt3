use crate::{
    error::{BuildError, Result},
    mapping::GenerationMode,
};
use std::{
    fs,
    path::{Path, PathBuf},
};

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "crate", "dyn", "else", "enum",
    "extern", "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct", "super",
    "trait", "true", "type", "unsafe", "use", "where", "while",
];

/// Verify that a string is a valid Rust identifier.
pub fn validate_identifier(name: &str, context: &'static str) -> Result<()> {
    if name.is_empty() {
        return Err(BuildError::InvalidIdentifier {
            context,
            name: name.to_owned(),
        });
    }
    // Allow raw identifier prefix r#
    let ident = name.strip_prefix("r#").unwrap_or(name);
    let mut chars = ident.chars();
    let first = chars.next().unwrap();
    if !(first.is_ascii_alphabetic() || first == '_') {
        return Err(BuildError::InvalidIdentifier {
            context,
            name: name.to_owned(),
        });
    }
    if !chars.all(|c| c.is_ascii_alphanumeric() || c == '_') {
        return Err(BuildError::InvalidIdentifier {
            context,
            name: name.to_owned(),
        });
    }
    if !name.starts_with("r#") && RUST_KEYWORDS.contains(&ident) {
        return Err(BuildError::InvalidIdentifier {
            context,
            name: name.to_owned(),
        });
    }
    Ok(())
}

/// Verify that a string is a valid Rust path (e.g. `crate::settings::GuiDefaults`).
pub fn validate_rust_path(path: &str, context: &'static str) -> Result<()> {
    let trimmed = path.trim();
    if trimmed.is_empty() {
        return Err(BuildError::InvalidRustPath {
            context,
            path: path.to_owned(),
        });
    }
    let without_leading = trimmed.strip_prefix("::").unwrap_or(trimmed);
    for (i, segment) in without_leading.split("::").enumerate() {
        if segment.is_empty() {
            return Err(BuildError::InvalidRustPath {
                context,
                path: path.to_owned(),
            });
        }
        if i == 0 && matches!(segment, "crate" | "super" | "self") {
            continue;
        }
        validate_identifier(segment, context)?;
    }
    Ok(())
}

/// Generate the Rust source code for the struct initializer.
pub fn generate_source(
    rust_struct: &str,
    mode: &GenerationMode,
    field_initializers: &[(String, String)],
) -> String {
    let mut out = String::new();
    out.push_str("// Generated by scinumtools3-build. DO NOT EDIT.\n\n");

    match mode {
        GenerationMode::Const(const_name) => {
            out.push_str(&format!("pub const {const_name}: {rust_struct} =\n"));
            out.push_str(&format!("    {rust_struct} {{\n"));
            for (field, expr) in field_initializers {
                out.push_str(&format!("        {field}: {expr},\n"));
            }
            out.push_str("    };\n");
        }
        GenerationMode::Factory(factory_name) => {
            out.push_str(&format!("pub fn {factory_name}() -> {rust_struct} {{\n"));
            out.push_str(&format!("    {rust_struct} {{\n"));
            for (field, expr) in field_initializers {
                out.push_str(&format!("        {field}: {expr},\n"));
            }
            out.push_str("    }\n");
            out.push_str("}\n");
        }
    }

    out
}

static COUNTER: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);

/// Atomically write content to `destination_path` only if content has changed.
/// Returns `true` if the file was written, `false` if unchanged.
pub fn write_if_changed(destination_path: &Path, content: &str) -> Result<bool> {
    if let Ok(existing) = fs::read(destination_path) {
        if existing == content.as_bytes() {
            return Ok(false);
        }
    }

    if let Some(parent) = destination_path.parent() {
        fs::create_dir_all(parent)?;
    }

    let file_name = destination_path
        .file_name()
        .and_then(|s| s.to_str())
        .unwrap_or("output.rs");
    let count = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
    let temp_path: PathBuf = destination_path.with_file_name(format!(
        "{file_name}.tmp.{}.{count}",
        std::process::id()
    ));

    fs::write(&temp_path, content)?;
    fs::rename(&temp_path, destination_path)?;

    Ok(true)
}
